#!/usr/bin/env python3
"""Tiny stand-in for UnrealHeaderTool, used only by the headless test build.

* Writes an empty `<Header>.generated.h` for every plugin header that includes one.
* Parses UENUM / USTRUCT / UPROPERTY declarations and writes `HeadlessReflection.generated.inl`,
  which reads JSON into the row structs by UPROPERTY name - the way FJsonObjectConverter and the
  DataTable JSON importer do in the editor - and reports keys that match no property (the editor
  would silently ignore those, so a typo in a data file would go unnoticed).

Usage: gen_reflection.py <plugin Public dir> <output dir> <RootStruct> [<RootStruct> ...]
"""

import os
import re
import sys

ENUM_RE = re.compile(r"UENUM\s*\([^)]*\)\s*enum\s+class\s+(\w+)\s*:\s*\w+\s*\{(.*?)\};", re.S)
STRUCT_RE = re.compile(r"USTRUCT\s*\([^)]*\)\s*struct\s+(?:\w+_API\s+)?(\w+)(?:\s*:\s*public\s+(\w+))?\s*\{")


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def balanced(text, start, open_ch, close_ch):
    """Index just past the bracket that closes the one at text[start]."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == open_ch:
            depth += 1
        elif text[i] == close_ch:
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("unbalanced brackets")


def parse_header(text, enums, structs):
    text = strip_comments(text)
    for match in ENUM_RE.finditer(text):
        body = re.sub(r"UMETA\s*\((?:[^()]|\([^()]*\))*\)", "", match.group(2))
        values = []
        for entry in body.split(","):
            name = entry.split("=")[0].strip()
            if name:
                values.append(name)
        enums[match.group(1)] = values

    for match in STRUCT_RE.finditer(text):
        name, base = match.group(1), match.group(2)
        body_start = match.end() - 1
        body = text[body_start:balanced(text, body_start, "{", "}")]
        props = []
        pos = 0
        while True:
            at = body.find("UPROPERTY", pos)
            if at < 0:
                break
            paren = body.index("(", at)
            after = balanced(body, paren, "(", ")")
            decl = body[after:body.index(";", after)].split("=")[0].strip()
            ident = re.search(r"(\w+)\s*$", decl).group(1)
            ptype = decl[: decl.rfind(ident)].strip()
            props.append((ptype, ident))
            pos = after
        structs[name] = {"base": base, "props": props}


def referenced_structs(ptype, structs):
    return [t for t in re.findall(r"\b(F\w+)\b", ptype) if t in structs]


def main():
    public_dir, out_dir, roots = sys.argv[1], sys.argv[2], sys.argv[3:]
    os.makedirs(out_dir, exist_ok=True)

    enums, structs = {}, {}
    for folder, _, files in os.walk(public_dir):
        for file_name in sorted(files):
            if not file_name.endswith(".h"):
                continue
            with open(os.path.join(folder, file_name), encoding="utf-8") as handle:
                text = handle.read()
            for generated in re.findall(r'#include\s+"(\w+\.generated\.h)"', text):
                with open(os.path.join(out_dir, generated), "w", encoding="utf-8") as stub:
                    stub.write("#pragma once\n// Headless stand-in for UnrealHeaderTool output.\n")
            parse_header(text, enums, structs)

    # Structs reachable from the data-table rows we load.
    needed, queue = [], list(roots)
    while queue:
        current = queue.pop(0)
        if current in needed or current not in structs:
            continue
        needed.append(current)
        for ptype, _ in structs[current]["props"]:
            queue.extend(referenced_structs(ptype, structs))

    used_enums = set()
    for struct_name in needed:
        for ptype, _ in structs[struct_name]["props"]:
            used_enums.update(t for t in re.findall(r"\b(E\w+)\b", ptype) if t in enums)

    out = ["// Generated by gen_reflection.py - do not edit.", "#pragma once", "", "namespace GOHeadless", "{"]
    for enum_name in sorted(used_enums):
        values = enums[enum_name]
        table = ", ".join('{{"{0}", {1}::{0}}}'.format(v, enum_name) for v in values)
        out += [
            "inline bool ParseEnum(const std::string& S, {0}& Out)".format(enum_name),
            "{",
            "\tstatic const std::pair<const char*, {0}> Table[] = {{ {1} }};".format(enum_name, table),
            "\tfor (const auto& Entry : Table)",
            "\t{",
            '\t\tif (S == Entry.first || S == std::string("{0}::") + Entry.first) {{ Out = Entry.second; return true; }}'.format(enum_name),
            "\t}",
            "\treturn false;",
            "}",
            "inline void ReadValue(const FJsonNode& N, {0}& Out, FReadContext& C, const std::string& Path)".format(enum_name),
            "{",
            '\tif (N.Kind != FJsonNode::EKind::String || !ParseEnum(N.String, Out)) {{ C.Fail(Path, "expected a {0} value"); }}'.format(enum_name),
            "}",
            "",
        ]

    for struct_name in needed:
        out.append("void ReadValue(const FJsonNode& N, {0}& Out, FReadContext& C, const std::string& Path);".format(struct_name))
    out += [
        "",
        "template <typename T>",
        "void ReadValue(const FJsonNode& N, TArray<T>& Out, FReadContext& C, const std::string& Path)",
        "{",
        '\tif (N.Kind != FJsonNode::EKind::Array) { C.Fail(Path, "expected an array"); return; }',
        "\tOut.Reset();",
        "\tfor (size_t I = 0; I < N.Array.size(); ++I)",
        "\t{",
        "\t\tT Item{};",
        '\t\tReadValue(N.Array[I], Item, C, Path + "[" + std::to_string(I) + "]");',
        "\t\tOut.Add(Item);",
        "\t}",
        "}",
        "",
    ]

    for struct_name in needed:
        info = structs[struct_name]
        is_row = info["base"] == "FTableRowBase"
        out += [
            "inline void ReadValue(const FJsonNode& N, {0}& Out, FReadContext& C, const std::string& Path)".format(struct_name),
            "{",
            '\tif (N.Kind != FJsonNode::EKind::Object) { C.Fail(Path, "expected an object"); return; }',
            "\tfor (const auto& KV : N.Object)",
            "\t{",
            "\t\tconst std::string& Key = KV.first;",
        ]
        if is_row:
            out.append('\t\tif (Key == "Name") { continue; }')
        for _, prop in info["props"]:
            out.append('\t\tif (Key == "{0}") {{ ReadValue(KV.second, Out.{0}, C, Path + ".{0}"); continue; }}'.format(prop))
        out += [
            '\t\tC.Fail(Path, "unknown property \'" + Key + "\' (not a UPROPERTY of {0})");'.format(struct_name),
            "\t}",
            "}",
            "",
        ]
    out.append("}")

    with open(os.path.join(out_dir, "HeadlessReflection.generated.inl"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(out) + "\n")
    print("gen_reflection: {} enums, {} structs".format(len(used_enums), len(needed)))


if __name__ == "__main__":
    main()
